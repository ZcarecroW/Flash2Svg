// Builds what the command line loads into a browser to encode MP4 and WebM (src/cli/video-page.ts)
// as a string module (src/cli/video-page.generated.ts). Run by scripts/build.mjs, or on its own after
// changing src/core/video-codecs.ts.
import * as esbuild from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function buildVideoPage() {
	const r = await esbuild.build({
		entryPoints: [join(repo, "src/cli/video-page.ts")],
		bundle: true,
		minify: true,
		format: "iife",
		target: "chrome120",
		write: false,
		legalComments: "none",
	});
	const code = r.outputFiles[0].text.trim();
	writeFileSync(
		join(repo, "src/cli/video-page.generated.ts"),
		`// Generated by scripts/build-video-page.mjs from src/cli/video-page.ts: don't edit.\n/** The browser's video and audio encoders behind f2sPick, f2sOpen, f2sEncode, f2sClose, f2sSound. */\nexport const VIDEO_PAGE = ${JSON.stringify(code)};\n`,
	);
	return code.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	console.log(`video page: ${((await buildVideoPage()) / 1024).toFixed(1)} KB`);
}
