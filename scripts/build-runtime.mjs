// Bundles the player runtime (src/player/runtime.ts) into a minified IIFE and stores it as a
// string module the player emitter imports (src/core/emit/runtime-code.generated.ts).
import * as esbuild from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The runtime's own member names, shortened in the bundle (esbuild mangleProps). Only names that
 * are never a DOM/Web API property, part of the public API (svg.flash2svg) or a field of the JSON
 * program (src/player/format.ts) may be listed: every property access with the name is renamed.
 */
const INTERNAL = [
	"updateAdvance", "animTransform", "animAlpha", "hiddenTab", "offView", "resting", "rest",
	"playSounds", "stopStreams", "streamSync", "streams", "enteredFrame", "layerNodes", "maskIds",
	"buttonState", "seqIndex", "lastM", "filterRef", "colorWrap", "vanim", "anims", "runActions",
	"labelAt", "setFrame", "gotoFrame", "frameLoop", "inTick", "listeners", "mixer", "voices",
	"quiet", "clock", "tnode", "fnode", "owner", "items", "passes", "fresh", "ended", "flows", "adv",
	"age", "named", "dispose", "playing", "running", "startAll", "stopAll", "bufs", "born", "held",
	"emit", "node", "render", "sync", "tick", "step", "kind", "els", "player", "time", "last", "raf",
	"rate", "defs", "svg", "voice", "trigger", "hold", "pos", "mpart", "mels", "mcopies", "mrat", "mfra",
];

/**
 * Four builds: with or without the sound code (programs with sounds) and the morph code
 * (programs with shape tweens as path morphs): PLAYER_RUNTIMES[(sound ? 1 : 0) + (morph ? 2 : 0)].
 */
export async function buildRuntime() {
	const build = async (sound, morph) => {
		const r = await esbuild.build({
			entryPoints: [join(repo, "src/player/runtime.ts")],
			bundle: true,
			minify: true,
			format: "iife",
			target: "es2020",
			write: false,
			legalComments: "none",
			define: { __SOUND__: String(sound), __MORPH__: String(morph) },
			mangleProps: new RegExp(`^(${INTERNAL.join("|")})$`),
		});
		// "]]>" can't appear in CDATA-less script text either; guard anyway
		return r.outputFiles[0].text.trim().replace(/<\/script/gi, "<\\/script");
	};
	const all = await Promise.all([build(false, false), build(true, false), build(false, true), build(true, true)]);
	const out =
		`// Generated by scripts/build-runtime.mjs from src/player/runtime.ts. Do not edit.\n` +
		`// [plain, with sound, with morphs, with sound and morphs]\n` +
		`export const PLAYER_RUNTIMES = ${JSON.stringify(all)};\n`;
	writeFileSync(join(repo, "src/core/emit/runtime-code.generated.ts"), out);
	return all.map((s) => s.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const kb = (x) => (x / 1024).toFixed(1) + " KB";
	const [plain, sound, morph, both] = await buildRuntime();
	console.log(`player runtime: ${kb(plain)}, with sound ${kb(sound)}, with morphs ${kb(morph)}, with both ${kb(both)}`);
}
